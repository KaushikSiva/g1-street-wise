import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base=process.env.STREETWISE_URL||'http://127.0.0.1:8192';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/?robot=1');
await page.waitForFunction(()=>window.forkRobot?.ready,null,{timeout:120000});
await page.locator('#live-seed').fill('30002');
await page.locator('#live-run').click();
await page.waitForFunction(()=>!document.querySelector('#live-results').hidden,null,{timeout:240000});
const results=await page.evaluate(()=>({seed:window.forkRobot.current.seed,badge:document.querySelector('#replay-source').textContent,status:document.querySelector('#live-status').textContent,summary:document.querySelector('#live-results').textContent}));
assert.equal(results.seed,30002);assert.match(results.badge,/FRESH MUJOCO/);assert.match(results.status,/Fresh comparison ready/);
await page.locator('#after').click();assert.equal(await page.evaluate(()=>window.forkRobot.mode),'after');
assert.equal(await page.evaluate(()=>window.forkRobot.current.seed),30002);
await page.locator('#robot-play').click();await page.waitForTimeout(600);assert(await page.evaluate(()=>window.forkRobot.time)>0);
await page.locator('#robot-play').click();
await fs.mkdir('artifacts/fork/live-demo',{recursive:true});
await page.locator('#live-lab').screenshot({path:'artifacts/fork/live-demo/controls.png'});
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
assert.deepEqual(errors,[]);
await fs.writeFile('artifacts/fork/live-demo/browser-check.json',JSON.stringify({base,...results,modeSwitch:true,playback:true,mobileOverflow:false,errors},null,2));
await browser.close();console.log('PASS fresh scenario, same-seed policies, playback, mobile layout.');
